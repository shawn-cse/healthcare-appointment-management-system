-- Exact Green Hospital PostgreSQL Schema (mirrors existing Django-PostgreSQL schema)
-- Uses IF NOT EXISTS so running against an existing database preserves all data and constraints.

CREATE TABLE IF NOT EXISTS hospital_user (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  password VARCHAR(128) NOT NULL,
  last_login TIMESTAMPTZ NULL,
  is_superuser BOOLEAN NOT NULL DEFAULT FALSE,
  username VARCHAR(150) NOT NULL UNIQUE,
  first_name VARCHAR(150) NOT NULL DEFAULT '',
  last_name VARCHAR(150) NOT NULL DEFAULT '',
  email VARCHAR(254) NOT NULL DEFAULT '',
  is_staff BOOLEAN NOT NULL DEFAULT FALSE,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  date_joined TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  role VARCHAR(16) NOT NULL DEFAULT 'patient',
  phone VARCHAR(16) NULL UNIQUE,
  dob DATE NULL,
  nid VARCHAR(30) NOT NULL DEFAULT '',
  address TEXT NOT NULL DEFAULT '',
  avatar VARCHAR(100) NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS hospital_user_role_idx ON hospital_user (role);
CREATE UNIQUE INDEX IF NOT EXISTS unique_user_email_case_insensitive
  ON hospital_user (LOWER(email))
  WHERE (email <> '');

CREATE TABLE IF NOT EXISTS hospital_department (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL UNIQUE,
  slug VARCHAR(50) NOT NULL UNIQUE,
  description VARCHAR(255) NOT NULL DEFAULT '',
  icon VARCHAR(32) NOT NULL DEFAULT 'heart-pulse',
  is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS hospital_hospitalpolicy (
  id SMALLINT PRIMARY KEY DEFAULT 1 CHECK (id >= 0),
  default_notice_hours INTEGER NOT NULL DEFAULT 24 CHECK (default_notice_hours >= 0),
  default_advance_days INTEGER NOT NULL DEFAULT 60 CHECK (default_advance_days >= 0),
  default_payment_hours INTEGER NOT NULL DEFAULT 4 CHECK (default_payment_hours >= 0),
  default_cancel_mode VARCHAR(10) NOT NULL DEFAULT 'percent',
  default_cancel_value NUMERIC(9,2) NOT NULL DEFAULT 10.00,
  default_hospital_mode VARCHAR(10) NOT NULL DEFAULT 'percent',
  default_hospital_value NUMERIC(9,2) NOT NULL DEFAULT 10.00,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS hospital_chamber (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  building VARCHAR(80) NOT NULL DEFAULT 'Building 1',
  name VARCHAR(150) NOT NULL,
  room_number VARCHAR(50) NOT NULL DEFAULT 'Chamber 302',
  floor VARCHAR(50) NOT NULL DEFAULT '3rd Floor',
  description VARCHAR(255) NOT NULL DEFAULT 'Building 1, chamber 302',
  address VARCHAR(255) NOT NULL DEFAULT 'Mirpur, Dhaka',
  contact_number VARCHAR(120) NOT NULL DEFAULT '+88096100016211',
  department_id BIGINT NULL REFERENCES hospital_department(id) ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS hospital_chamber_department_id_idx ON hospital_chamber (department_id);

CREATE TABLE IF NOT EXISTS hospital_doctorprofile (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL UNIQUE REFERENCES hospital_user(id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
  department_id BIGINT NOT NULL REFERENCES hospital_department(id) ON DELETE RESTRICT DEFERRABLE INITIALLY DEFERRED,
  chamber_id BIGINT NULL REFERENCES hospital_chamber(id) ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED,
  chamber_days VARCHAR(50) NOT NULL DEFAULT '0,2',
  gender VARCHAR(10) NOT NULL DEFAULT 'male',
  qualifications TEXT NOT NULL DEFAULT '',
  designation VARCHAR(150) NOT NULL DEFAULT 'Consultant',
  registration_number VARCHAR(100) NOT NULL DEFAULT '',
  experience_years SMALLINT NOT NULL DEFAULT 0 CHECK (experience_years >= 0),
  biography TEXT NOT NULL DEFAULT '',
  initial_fee NUMERIC(9,2) NOT NULL DEFAULT 1000.00,
  followup_fee NUMERIC(9,2) NOT NULL DEFAULT 800.00,
  followup_within_days INTEGER NOT NULL DEFAULT 30 CHECK (followup_within_days >= 0),
  report_fee NUMERIC(9,2) NOT NULL DEFAULT 500.00,
  max_patients_per_session SMALLINT NOT NULL DEFAULT 30 CHECK (max_patients_per_session >= 0),
  hospital_share_mode VARCHAR(10) NOT NULL DEFAULT 'percent',
  hospital_share_value NUMERIC(9,2) NOT NULL DEFAULT 10.00,
  booking_notice_hours INTEGER NOT NULL DEFAULT 24 CHECK (booking_notice_hours >= 0),
  booking_advance_days INTEGER NOT NULL DEFAULT 60 CHECK (booking_advance_days >= 0),
  payment_policy VARCHAR(10) NOT NULL DEFAULT 'on_day',
  payment_deadline_hours INTEGER NOT NULL DEFAULT 4 CHECK (payment_deadline_hours >= 0),
  cancel_fee_mode VARCHAR(10) NOT NULL DEFAULT 'percent',
  cancel_fee_value NUMERIC(9,2) NOT NULL DEFAULT 10.00,
  title_prefix VARCHAR(40) NOT NULL DEFAULT 'Dr.',
  institute VARCHAR(200) NOT NULL DEFAULT '',
  room_number VARCHAR(50) NOT NULL DEFAULT 'Chamber 302',
  chamber_address VARCHAR(255) NOT NULL DEFAULT 'Mirpur, Dhaka',
  contact_number VARCHAR(100) NOT NULL DEFAULT '+88096100016211',
  is_available BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE INDEX IF NOT EXISTS hospital_doctorprofile_department_id_idx ON hospital_doctorprofile (department_id);
CREATE INDEX IF NOT EXISTS hospital_doctorprofile_chamber_id_idx ON hospital_doctorprofile (chamber_id);

CREATE TABLE IF NOT EXISTS hospital_doctorprofile_receptionists (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  doctorprofile_id BIGINT NOT NULL REFERENCES hospital_doctorprofile(id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
  user_id BIGINT NOT NULL REFERENCES hospital_user(id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
  UNIQUE (doctorprofile_id, user_id)
);

CREATE INDEX IF NOT EXISTS hospital_doctorprofile_rec_doc_idx ON hospital_doctorprofile_receptionists (doctorprofile_id);
CREATE INDEX IF NOT EXISTS hospital_doctorprofile_rec_user_idx ON hospital_doctorprofile_receptionists (user_id);

CREATE TABLE IF NOT EXISTS hospital_weeklyavailability (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  doctor_id BIGINT NOT NULL REFERENCES hospital_doctorprofile(id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
  weekday SMALLINT NOT NULL CHECK (weekday >= 0),
  start_time TIME WITHOUT TIME ZONE NOT NULL,
  end_time TIME WITHOUT TIME ZONE NOT NULL,
  duration_minutes SMALLINT NOT NULL DEFAULT 30 CHECK (duration_minutes >= 0),
  capacity SMALLINT NOT NULL DEFAULT 1 CHECK (capacity >= 0),
  active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE INDEX IF NOT EXISTS hospital_weeklyavailability_doctor_id_idx ON hospital_weeklyavailability (doctor_id);

CREATE TABLE IF NOT EXISTS hospital_appointmentslot (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  doctor_id BIGINT NOT NULL REFERENCES hospital_doctorprofile(id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
  template_id BIGINT NULL REFERENCES hospital_weeklyavailability(id) ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED,
  date DATE NOT NULL,
  start_time TIME WITHOUT TIME ZONE NOT NULL,
  end_time TIME WITHOUT TIME ZONE NOT NULL,
  capacity SMALLINT NOT NULL DEFAULT 1 CHECK (capacity >= 0),
  is_open BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT unique_doctor_slot UNIQUE (doctor_id, date, start_time)
);

CREATE INDEX IF NOT EXISTS hospital_appointmentslot_doctor_id_idx ON hospital_appointmentslot (doctor_id);
CREATE INDEX IF NOT EXISTS hospital_appointmentslot_date_idx ON hospital_appointmentslot (date);
CREATE INDEX IF NOT EXISTS hospital_appointmentslot_template_id_idx ON hospital_appointmentslot (template_id);

CREATE TABLE IF NOT EXISTS hospital_appointment (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reference VARCHAR(20) NOT NULL UNIQUE,
  serial_number INTEGER NOT NULL DEFAULT 1 CHECK (serial_number >= 0),
  slot_id BIGINT NOT NULL REFERENCES hospital_appointmentslot(id) ON DELETE RESTRICT DEFERRABLE INITIALLY DEFERRED,
  patient_id BIGINT NULL REFERENCES hospital_user(id) ON DELETE RESTRICT DEFERRABLE INITIALLY DEFERRED,
  guest_name VARCHAR(150) NOT NULL,
  guest_phone VARCHAR(16) NOT NULL,
  guest_dob DATE NULL,
  visit_type VARCHAR(10) NOT NULL DEFAULT 'first',
  status VARCHAR(14) NOT NULL DEFAULT 'confirmed',
  payment_status VARCHAR(20) NOT NULL DEFAULT 'unpaid',
  payment_method VARCHAR(10) NOT NULL DEFAULT 'cash',
  source VARCHAR(10) NOT NULL DEFAULT 'web',
  fee NUMERIC(9,2) NOT NULL,
  cancel_mode_snapshot VARCHAR(10) NOT NULL DEFAULT 'percent',
  cancel_value_snapshot NUMERIC(9,2) NOT NULL DEFAULT 0.00,
  hospital_cut NUMERIC(9,2) NOT NULL DEFAULT 0.00,
  doctor_cut NUMERIC(9,2) NOT NULL DEFAULT 0.00,
  payment_due_at TIMESTAMPTZ NULL,
  notes TEXT NOT NULL DEFAULT '',
  cancellation_reason TEXT NOT NULL DEFAULT '',
  cancelled_by_id BIGINT NULL REFERENCES hospital_user(id) ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED,
  created_by_id BIGINT NULL REFERENCES hospital_user(id) ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS hospital_appointment_slot_id_idx ON hospital_appointment (slot_id);
CREATE INDEX IF NOT EXISTS hospital_appointment_patient_id_idx ON hospital_appointment (patient_id);
CREATE INDEX IF NOT EXISTS hospital_appointment_guest_phone_idx ON hospital_appointment (guest_phone);
CREATE INDEX IF NOT EXISTS hospital_appointment_status_idx ON hospital_appointment (status);
CREATE INDEX IF NOT EXISTS hospital_appointment_payment_status_idx ON hospital_appointment (payment_status);

CREATE TABLE IF NOT EXISTS hospital_paymenttransaction (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  appointment_id BIGINT NOT NULL REFERENCES hospital_appointment(id) ON DELETE RESTRICT DEFERRABLE INITIALLY DEFERRED,
  kind VARCHAR(8) NOT NULL DEFAULT 'charge',
  method VARCHAR(12) NOT NULL,
  status VARCHAR(14) NOT NULL DEFAULT 'initiated',
  amount NUMERIC(9,2) NOT NULL,
  external_id VARCHAR(40) NULL UNIQUE,
  validation_id VARCHAR(90) NOT NULL DEFAULT '',
  bank_transaction_id VARCHAR(90) NOT NULL DEFAULT '',
  refund_reference VARCHAR(90) NOT NULL DEFAULT '',
  handled_by_id BIGINT NULL REFERENCES hospital_user(id) ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED,
  note VARCHAR(255) NOT NULL DEFAULT '',
  processed_at TIMESTAMPTZ NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS hospital_paymenttransaction_appointment_id_idx ON hospital_paymenttransaction (appointment_id);
CREATE INDEX IF NOT EXISTS hospital_paymenttransaction_handled_by_id_idx ON hospital_paymenttransaction (handled_by_id);

CREATE TABLE IF NOT EXISTS hospital_refundrequest (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  appointment_id BIGINT NOT NULL UNIQUE REFERENCES hospital_appointment(id) ON DELETE RESTRICT DEFERRABLE INITIALLY DEFERRED,
  amount NUMERIC(9,2) NOT NULL,
  mode VARCHAR(10) NOT NULL,
  status VARCHAR(12) NOT NULL DEFAULT 'pending',
  requested_by_id BIGINT NULL REFERENCES hospital_user(id) ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED,
  reviewed_by_id BIGINT NULL REFERENCES hospital_user(id) ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED,
  reason TEXT NOT NULL DEFAULT '',
  internal_note TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  reviewed_at TIMESTAMPTZ NULL,
  completed_at TIMESTAMPTZ NULL
);

CREATE INDEX IF NOT EXISTS hospital_refundrequest_requested_by_id_idx ON hospital_refundrequest (requested_by_id);
CREATE INDEX IF NOT EXISTS hospital_refundrequest_reviewed_by_id_idx ON hospital_refundrequest (reviewed_by_id);

CREATE TABLE IF NOT EXISTS hospital_complaint (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ticket_code VARCHAR(12) NOT NULL DEFAULT '',
  patient_id BIGINT NOT NULL REFERENCES hospital_user(id) ON DELETE RESTRICT DEFERRABLE INITIALLY DEFERRED,
  appointment_id BIGINT NULL REFERENCES hospital_appointment(id) ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED,
  subject VARCHAR(150) NOT NULL,
  category VARCHAR(20) NOT NULL DEFAULT 'support',
  message TEXT NOT NULL,
  attachment VARCHAR(100) NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'submitted',
  response TEXT NOT NULL DEFAULT '',
  admin_attachment VARCHAR(100) NULL,
  updated_by_id BIGINT NULL REFERENCES hospital_user(id) ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS hospital_complaint_ticket_code_idx ON hospital_complaint (ticket_code);
CREATE INDEX IF NOT EXISTS hospital_complaint_patient_id_idx ON hospital_complaint (patient_id);
CREATE INDEX IF NOT EXISTS hospital_complaint_appointment_id_idx ON hospital_complaint (appointment_id);
CREATE INDEX IF NOT EXISTS hospital_complaint_updated_by_id_idx ON hospital_complaint (updated_by_id);

CREATE TABLE IF NOT EXISTS hospital_complaintmessage (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  complaint_id BIGINT NOT NULL REFERENCES hospital_complaint(id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
  author_id BIGINT NOT NULL REFERENCES hospital_user(id) ON DELETE RESTRICT DEFERRABLE INITIALLY DEFERRED,
  message TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS hospital_complaintmessage_complaint_id_idx ON hospital_complaintmessage (complaint_id);
CREATE INDEX IF NOT EXISTS hospital_complaintmessage_author_id_idx ON hospital_complaintmessage (author_id);

CREATE TABLE IF NOT EXISTS hospital_auditevent (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_id BIGINT NULL REFERENCES hospital_user(id) ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED,
  action VARCHAR(100) NOT NULL,
  target VARCHAR(160) NOT NULL,
  detail TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS hospital_auditevent_actor_id_idx ON hospital_auditevent (actor_id);
